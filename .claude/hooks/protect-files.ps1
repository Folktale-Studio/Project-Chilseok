# PreToolUse hook (Edit|Write|MultiEdit|NotebookEdit)
# - Unity serialized assets, ThirdParty, project/package settings: BLOCK (exit 2)
# - Harness files (.claude/**, CLAUDE.md): ASK the human
# - Everything else: allow (exit 0)
# See docs/adr/0003-unity-assets-via-editor-code.md and docs/harness/README.md
# Messages are ASCII on purpose: Windows PowerShell 5.1 may garble non-ASCII on stderr.

$ErrorActionPreference = 'Stop'

try {
    $raw = [Console]::In.ReadToEnd()
    $payload = $raw | ConvertFrom-Json
} catch {
    # Cannot parse input: do not block work, but say so.
    [Console]::Error.WriteLine("[protect-files] could not parse hook input; allowing.")
    exit 0
}

$toolInput = $payload.tool_input
$path = $null
if ($toolInput) {
    if ($toolInput.file_path) { $path = [string]$toolInput.file_path }
    elseif ($toolInput.notebook_path) { $path = [string]$toolInput.notebook_path }
}
if ([string]::IsNullOrWhiteSpace($path)) { exit 0 }

# Project root = two levels above this script (.claude/hooks/ -> project)
$root = (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent).TrimEnd('\', '/')

if (-not [System.IO.Path]::IsPathRooted($path)) {
    $base = $root
    if ($payload.cwd) { $base = [string]$payload.cwd }
    $path = Join-Path $base $path
}
$full = [System.IO.Path]::GetFullPath($path)

$rootWithSep = $root + [System.IO.Path]::DirectorySeparatorChar
if (-not $full.StartsWith($rootWithSep, [System.StringComparison]::OrdinalIgnoreCase)) {
    exit 0   # outside the project: not this hook's job
}

$rel = $full.Substring($rootWithSep.Length).Replace('\', '/')
$relLower = $rel.ToLowerInvariant()

function Block([string]$reason) {
    [Console]::Error.WriteLine("[protect-files] BLOCKED: $rel")
    [Console]::Error.WriteLine("Reason: $reason")
    [Console]::Error.WriteLine("Do not edit this file as text. Use an editor menu script in Assets/Chilseok/Editor/, a Unity MCP tool, or tell the human exactly what to change in the Inspector. (ADR-0003)")
    exit 2
}

function Ask([string]$reason) {
    $out = @{
        hookSpecificOutput = @{
            hookEventName            = 'PreToolUse'
            permissionDecision       = 'ask'
            permissionDecisionReason = $reason
        }
    } | ConvertTo-Json -Compress -Depth 4
    [Console]::Out.WriteLine($out)
    exit 0
}

# 1) Protected folders
$blockedPrefixes = @(
    'assets/thirdparty/',
    'projectsettings/',
    'library/',
    'usersettings/',
    'temp/'
)
foreach ($p in $blockedPrefixes) {
    if ($relLower.StartsWith($p)) { Block "protected folder '$p' (third-party / Unity-managed)" }
}

# 2) Package files
if ($relLower -eq 'packages/manifest.json' -or $relLower -eq 'packages/packages-lock.json') {
    Block "package changes are done by the human in Package Manager"
}

# 3) Unity serialized asset types
$blockedExtensions = @('.meta', '.unity', '.prefab', '.controller', '.asset', '.inputactions', '.anim', '.mat', '.overridecontroller', '.mask', '.playable', '.signal')
$ext = [System.IO.Path]::GetExtension($relLower)
if ($blockedExtensions -contains $ext) { Block "Unity serialized asset ($ext)" }

# 4) Harness self-modification needs a human
if ($relLower -eq 'claude.md' -or $relLower.StartsWith('.claude/')) {
    Ask "Harness file '$rel' controls the AI's own guardrails. A human must approve this edit."
}

exit 0
